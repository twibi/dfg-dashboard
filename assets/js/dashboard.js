  /* MKD -> selected unit. Percentages are shares of the selected basis's
     annual total for that year, so the total line itself reads 100 %. */
  function xform(mkd, denom) {
    if (mkd === null || mkd === undefined) return null;
    if (state.unit === "eur") return Math.round(mkd / RATE * 100) / 100;
    if (state.unit === "pct") {
      if (!denom) return null;
      return mkd / denom * 100;
    }
    return mkd;
  }

  function formatter(unit) {
    return unit === "pct"
      ? function (v) { return fmtPct(v) + " %"; }
      : function (v) { return fmtMoney(v, unit) + " " + moneySuffix(unit); };
  }

  function axisMeta(values, unit) {
    var max = 0;
    values.forEach(function (v) {
      if (v !== null && v !== undefined && v > max) max = v;
    });
    if (unit === "pct") return { div: 1, suffix: "%", pct: true };
    var big = unit === "eur" ? max >= 1e6 : max >= 1e8;
    return { div: big ? 1e6 : 1, pct: false,
             suffix: big ? "млн " + moneySuffix(unit) : moneySuffix(unit) };
  }

  function axisTick(meta) {
    if (meta.pct) return function (v) { return fmtPctTick(v); };
    return function (v) {
      var x = v / meta.div;
      if (meta.div === 1) return group(x, 0);
      return group(x, Math.abs(x) < 10 ? 1 : 0);
    };
  }

