  /* ------------------------------------------------------- PNG export */
  /* Chart.js defers its paint to requestAnimationFrame, which the browser
     suspends while the tab is hidden — so an export taken at that moment
     (or mid-animation) would be blank. Force a synchronous paint first. */
  function paintNow() {
    if (!chart) return null;
    var anim = chart.options.animation;
    chart.options.animation = false;
    chart.update("none");
    chart.draw();
    return anim;
  }

  function restorePaint(anim) {
    if (!chart) return;
    chart.options.animation = anim;
    chart.update("none");
    chart.draw();
  }

  function exportPNG() {
    var anim = paintNow();

    var src = canvas;
    var pad = 36;
    var headH = ins.textContent ? 96 : 66;

    var out = document.createElement("canvas");
    out.width = src.width;
    out.height = src.height + headH;
    var ctx = out.getContext("2d");

    ctx.fillStyle = "#ffffff";
    ctx.fillRect(0, 0, out.width, out.height);

    ctx.fillStyle = MAIN;
    ctx.font = "700 26px 'Segoe UI', Arial, sans-serif";
    ctx.textBaseline = "top";
    ctx.fillText(fitText(ctx, h1.textContent, out.width - pad * 2), pad, pad - 6);
    if (ins.textContent) {
      ctx.fillStyle = "#1c2430";
      ctx.font = "italic 17px 'Segoe UI', Arial, sans-serif";
      ctx.fillText(fitText(ctx, ins.textContent, out.width - pad * 2), pad, pad + 34);
    }

    ctx.drawImage(src, 0, headH);

    var a = document.createElement("a");
    a.href = out.toDataURL("image/png");
    a.download = "dfg-" + state.level + "-" + YEARS[state.from] + "-" +
                 YEARS[state.to] + ".png";
    a.click();

    restorePaint(anim);
  }

  function fitText(ctx, text, maxW) {
    if (ctx.measureText(text).width <= maxW) return text;
    var t = text;
    while (t.length > 1 && ctx.measureText(t + "…").width > maxW) t = t.slice(0, -1);
    return t + "…";
  }

  pngBtn.addEventListener("click", exportPNG);

  refresh();
