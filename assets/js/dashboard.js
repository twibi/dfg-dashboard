  /* ------------------------------------------------------- PNG export */
  /* Chart.js defers its paint to requestAnimationFrame, which the browser
     suspends while the tab is hidden — so an export taken at that moment
     (or mid-animation) would be blank. Force a synchronous paint first. */
  function freeze(c) {
    var anim = c.options.animation;
    c.options.animation = false;
    c.update("none");
    c.draw();
    return anim;
  }

  function thaw(c, anim) {
    c.options.animation = anim;
    c.update("none");
    c.draw();
  }

  function exportPNG() {
    /* the select next to the button decides what goes into the picture */
    var parts = [];
    if (pngSel.value !== "bars" && chart) {
      parts.push({ chart: chart, src: canvas, title: null });
    }
    if (pngSel.value !== "line" && chart2) {
      parts.push({ chart: chart2, src: canvas2,
                   title: chart2Title.textContent });
    }
    if (!parts.length) return;

    var frozen = parts.map(function (p) {
      return { c: p.chart, anim: freeze(p.chart) };
    });

    var pad = 36;
    var gap = 26;
    var titleH = 30;
    var headH = ins.textContent ? 96 : 66;
    var bodyH = 0;
    parts.forEach(function (p, i) {
      bodyH += (p.title ? titleH : 0) + p.src.height + (i ? gap : 0);
    });

    var out = document.createElement("canvas");
    out.width = Math.max.apply(null, parts.map(function (p) { return p.src.width; }));
    out.height = headH + bodyH;
    var ctx = out.getContext("2d");

    ctx.fillStyle = "#ffffff";
    ctx.fillRect(0, 0, out.width, out.height);

    ctx.fillStyle = MAIN;
    ctx.font = "700 26px 'Segoe UI', Arial, sans-serif";
    ctx.textBaseline = "top";
    ctx.fillText(fitText(ctx, h1.textContent, out.width - pad * 2), pad, pad - 6);
    if (ins.textContent) {
      ctx.fillStyle = "#1c2430";
      ctx.font = "italic 17px 'Segoe UI', Arial, sans-serif";
      ctx.fillText(fitText(ctx, ins.textContent, out.width - pad * 2), pad, pad + 34);
    }

    var y = headH;
    parts.forEach(function (p, i) {
      if (i) y += gap;
      if (p.title) {
        ctx.fillStyle = INK;
        ctx.font = "700 18px 'Segoe UI', Arial, sans-serif";
        ctx.fillText(fitText(ctx, p.title, out.width - pad * 2), pad, y);
        y += titleH;
      }
      ctx.drawImage(p.src, 0, y);
      y += p.src.height;
    });

    var a = document.createElement("a");
    a.href = out.toDataURL("image/png");
    a.download = "dfg-" + state.level + "-" + YEARS[state.from] + "-" +
                 YEARS[state.to] + ".png";
    a.click();

    frozen.forEach(function (f) { thaw(f.c, f.anim); });
  }

  function fitText(ctx, text, maxW) {
    if (ctx.measureText(text).width <= maxW) return text;
    var t = text;
    while (t.length > 1 && ctx.measureText(t + "…").width > maxW) t = t.slice(0, -1);
    return t + "…";
  }

  pngBtn.addEventListener("click", exportPNG);

  refresh();
